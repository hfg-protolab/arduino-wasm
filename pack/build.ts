// ------------------------------------------------------------------------------------------

async function main() {
    const args = process.argv.slice(2);
    const arg = (k: string) => {
        const i = args.indexOf(k);
        return i >= 0 ? args[i + 1] : undefined;
    };
    const cfg = loadConfig(arg("--config") ?? join(REPO, "pack/config.json"));
    const outRoot = arg("--out") ?? join(REPO, ".build/packs");
    const only = arg("--boards")?.split(",");
    const boards = cfg.boards.filter((b) => (!only || only.includes(b.id)) && existsSync(join(TOOLCHAINS, b.toolchain, "cc1plus.wasm")));
    const skipped = cfg.boards.filter((b) => (!only || only.includes(b.id)) && !boards.includes(b));
    if (skipped.length) console.log(`skipping (no wasm toolchain in ${TOOLCHAINS}): ${skipped.map((b) => b.id).join(", ")}`);
    const outDir = join(outRoot, cfg.packVersion);
    const store = new Store(outDir);
    mkdirSync(join(outDir, "boards"), { recursive: true });
    const builds: BoardBuild[] = [];
    for (const b of boards) builds.push(await buildBoard(cfg, b, store, { forceProbe: args.includes("--force-probe"), pch: !args.includes("--no-pch") }));

    // Header blobs: per family (arch) the files identical on every board → shared blob; rest per board.
    const manifests: BoardManifest[] = [];
    for (const arch of ["avr", "esp32", "esp8266"] as const) {
        const fam = builds.filter((x) => x.manifest.arch === arch);
        if (!fam.length) continue;
        const content = new Map<string, Uint8Array>();
        const key = (bb: BoardBuild, p: string) => {
            const data = readBytes(bb.headers.get(p)!);
            const k = `${p}\0${sha256(data)}`;
            content.set(k, data);
            return k;
        };
        const keys = fam.map((bb) => new Set([...bb.headers.keys()].map((p) => key(bb, p))));
        const shared = [...keys[0]!].filter((k) => keys.every((s) => s.has(k))).sort();
        const sharedRef = store.put(writeBundle(shared.map((k) => ({ path: k.split("\0")[0]!, data: content.get(k)! }))), "awb");
        fam.forEach((bb, i) => {
            const own = [...keys[i]!].filter((k) => !shared.includes(k)).sort();
            const refs = [sharedRef];
            if (own.length) refs.push(store.put(writeBundle(own.map((k) => ({ path: k.split("\0")[0]!, data: content.get(k)! }))), "awb"));
            manifests.push({ ...bb.manifest, headers: refs });
        });
    }
    // PCH needs the complete manifest (tools + headers).
    for (const m of manifests) {
        const b = boards.find((x) => x.id === m.id)!;
        if (!b.pch || args.includes("--no-pch")) continue;
        const files = new Map<string, Uint8Array>();
        const { readBundle } = await import("../src/bundle");
        for (const h of m.headers) for (const e of readBundle(readBytes(join(outDir, h.file)))) files.set(e.path, e.data);
        m.pch = await generatePch(store, m, files);
    }
    // Stats (raw / Brotli per part) and manifests.
    for (const m of manifests) {
        const st: BoardManifest["stats"] = {};
        const add = (k: string, refs: FileRef[]) => (st[k] = { raw: refs.reduce((s, r) => s + r.size, 0), brotli: refs.reduce((s, r) => s + store.brotli(r), 0) });
        for (const t of ["cc1plus", "cc1", "as", "ld"] as ToolName[]) add(`tool:${t}`, [m.tools[t].js, m.tools[t].wasm]);
        add("headers", m.headers);
        if (m.pch) add("pch", [m.pch.gch]);
        add("libraries", m.libraries.flatMap((l) => [...(l.archive ? [l.archive] : []), ...(l.objects ?? [])]));
        add("linkFiles", m.link.files);
        if (m.link.lazy) {
            add("lazyIndex", [m.link.lazy.index]);
            add("lazyBase", [m.link.lazy.base]);
        }
        if (m.output.kind === "esp-image") add("images", m.output.images);
        if (m.output.kind === "esp8266-image") add("images", [m.output.eboot]);
        m.stats = st;
        writeFileSync(join(outDir, "boards", `${m.id}.json`), JSON.stringify(m, null, 1));
        const first = ["tool:cc1plus", "tool:as", "tool:ld", "headers", "linkFiles", "lazyIndex", "lazyBase", "images", "pch"].reduce((s, k) => s + (st[k]?.brotli ?? 0), 0);
        console.log(`[${m.id}] first download (cc1plus+as+ld, headers, link base${m.pch ? ", PCH" : ""}): ${MB(first)} MB Brotli`);
        for (const [k, x] of Object.entries(st)) console.log(`    ${k.padEnd(14)} ${MB(x.raw).padStart(8)} MB raw  ${MB(x.brotli).padStart(7)} MB br`);
    }
    const prev = existsSync(join(outDir, "index.json")) ? JSON.parse(readFileSync(join(outDir, "index.json"), "utf8")) : { boards: {} };
    const index = { format: 1, packVersion: cfg.packVersion, boards: { ...prev.boards, ...Object.fromEntries(manifests.map((m) => [m.id, `boards/${m.id}.json`])) }, licenses: "licenses.json" };
    writeFileSync(join(outDir, "index.json"), JSON.stringify(index, null, 1));
    const inPack = cfg.boards.filter((b) => b.id in index.boards);
    // Boards of an earlier run into the same pack dir keep their libraries in licenses.json.
    const kept = inPack
        .filter((b) => !builds.some((x) => x.manifest.id === b.id) && existsSync(join(outDir, "boards", `${b.id}.json`)))
        .map((b) => JSON.parse(readFileSync(join(outDir, "boards", `${b.id}.json`), "utf8")) as BoardManifest);
    writeFileSync(join(outDir, "licenses.json"), JSON.stringify(licenses({ ...cfg, boards: inPack }, builds, kept), null, 1));
    store.save();
    console.log(`pack written to ${outDir}`);
    void copyFileSync;
    void relative;
    void tmpdir;
}

if (import.meta.main) await main();
