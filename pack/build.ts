// Log parsing

interface GraphNode {
    name: string;
    version: string;
    path: string;
    deps: string[];
}

function parseDependencyGraph(log: string): Map<string, GraphNode> {
    const lines = log.split("\n");
    const start = lines.findIndex((l) => l.trim() === "Dependency Graph");
    const nodes = new Map<string, GraphNode>();
    if (start < 0) return nodes;
    const stack: GraphNode[] = [];
    for (const l of lines.slice(start + 1)) {
        const m = /^((?:\|   |    )*)\|-- (.+?)(?: @ (\S+))?(?: \((.*)\))?$/.exec(l);
        if (!m) break;
        const depth = m[1]!.length / 4;
        const name = m[2]!.trim();
        const path = /Path: ([^)]*?)(?:,|$)/.exec(m[4] ?? "")?.[1]?.trim() ?? "";
        let node = nodes.get(name);
        const fresh = !node;
        if (!node) {
            node = { name, version: m[3] ?? "", path, deps: [] };
            nodes.set(name, node);
        }
        stack.length = depth;
        const parent = stack[depth - 1];
        if (parent && !parent.deps.includes(name)) {
            // only record children at the parent's first (complete) listing
            if (parent.deps.length === 0 || !parent.deps.includes(name)) parent.deps.push(name);
        }
        stack[depth] = node;
        void fresh;
    }
    return nodes;
}

/** `-###` of the native driver for one pio command line (run in the project dir). */
function driverSteps(b: BoardConfig, cmdLine: string, cwd: string): string[][] {
    const argv = shellSplit(cmdLine);
    const bin = join(PKG, toolchainPackage(b), "bin");
    const r = run(join(bin, argv[0]!), ["-###", ...argv.slice(1)], { cwd, env: { ...process.env, PATH: `${bin}:${process.env.PATH}` } });
    const steps = r.stderr.split("\n").filter((l) => l.startsWith(" ")).map((l) => splitDriverLine(l.trim()));
    if (!steps.length) throw new Error(`no -### steps for ${cmdLine.slice(0, 200)}\n${r.stderr}`);
    return steps;
}

