/**
 * Pack builder (plan phase 1): from pack/config.json and a native PlatformIO install, writes
 * .build/packs/<packVersion>/ in the format of docs/pack-format.md.
 *
 *   bun pack/build.ts [--config pack/config.json] [--out .build/packs] [--boards uno,esp32dev]
 *                     [--force-probe] [--no-pch]
 *
 * Per board:
 *  1. probe build (`pio run -v`, every library) → flags, library archives, dependency graph
 *  2. cc1plus/cc1/as/ld argv from the native driver's `-###` (never `-v`), mapped onto the
 *     virtual file system of the AI Hub image (/opt/pio/packages, /opt/pio-libs, /work/project)
 *  3. library archives and framework archives with `--strip-debug`; ESP32: framework archives
 *     split into content-addressed members + symbol index + base blob (lazy linking)
 *  4. header closure (`-M`) of Arduino.h, every library header, the C/C++ std headers and the
 *     curated extra headers; per-family shared blob + per-board delta
 *  5. ESP32: PCH of Arduino.h, generated by the wasm cc1plus itself
 *  6. constant flash images, size limits, manifest
 */
