// File store

class Store {
    readonly files = new Map<string, FileRef>();
    private brCache: Record<string, number>;
    private brCachePath = join(WORK, "brotli-sizes.json");
    constructor(readonly dir: string) {
        mkdirSync(join(dir, "files"), { recursive: true });
        this.brCache = existsSync(this.brCachePath) ? JSON.parse(readFileSync(this.brCachePath, "utf8")) : {};
    }
    put(data: Uint8Array, ext: string): FileRef {
        const sha = sha256(data);
        const file = `files/${sha.slice(0, 32)}.${ext}`;
        const p = join(this.dir, file);
        if (!existsSync(p)) writeFileSync(p, data);
        const ref = { file, size: data.length, sha256: sha };
        this.files.set(file, ref);
        return ref;
    }
    brotli(ref: FileRef): number {
        let n = this.brCache[ref.sha256];
        if (n === undefined) {
            n = brotliSize(readBytes(join(this.dir, ref.file)));
            this.brCache[ref.sha256] = n;
        }
        return n;
    }
    save() {
        writeFileSync(this.brCachePath, JSON.stringify(this.brCache));
    }
}

