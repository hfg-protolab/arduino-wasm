// Paths: native → virtual (AI Hub image layout)

function makeVirtualizer(cfg: PackConfig, b: BoardConfig) {
    const pairs: Array<[string, string]> = [
        [projectDir(b.id), cfg.virtualRoots.project],
        [libsRoot(), cfg.virtualRoots.libs],
        [PKG, cfg.virtualRoots.packages],
    ];
    const v = (s: string) => {
        for (const [from, to] of pairs) if (s.includes(from)) s = s.split(from).join(to);
        return s;
    };
    /** virtual → native (absolute) */
    const n = (s: string) => {
        for (const [from, to] of pairs) if (s.startsWith(to + "/") || s === to) return from + s.slice(to.length);
        return s;
    };
    return { v, n };
}

